email = true
senha = true

// E && 

console.log(email && senha) // Resultado = true (já que os dois valores são verdadeiros)

// Ou || 

console.log(email || senha) // Resultado = true (já que pelo menos um dos valores é verdadeiro)

// Negação ! 

console.log(!email) // Resultado = false (negação do valor verdadeiro de email)