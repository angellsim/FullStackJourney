// Query Selector é como se fosse o seletor do CSS. Ele retorna o primeiro elemento que encontrar dentro da especificidade escolhida. 

// Também temos o Query Seletor All que é a mesma coisa porém ele retornará todos os valores que estiverem contidos dentro do elemento.

// Retorna apenas o primeiro elementos 
const guest3 = document.querySelector('#guest')

// Retorna todos os elementos encontrados
const guest4 = document.querySelectorAll('.guest')