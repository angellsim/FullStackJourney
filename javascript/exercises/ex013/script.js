let option = 1

switch (option) {
  case 1:
    console.log("A opção é 1")
    break
  case 2:
    console.log("A opção é 2")
    break
  case 3:
    console.log("A opção é 3")
    break
}

// É importante sempre ter um break logo após o comando do switch-case porque se não o código executará todos os cases posteriores à ele. 